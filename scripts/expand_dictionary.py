def main() -> int:
    dest = TERMS_DIR / "expanded.json"
    existing = [e for e in load_raw_terms() if e.get("_file") != dest.name]
    seen_pairs = {(e["fa"].casefold(), e["en"].casefold()) for e in existing}
    fa_counts: dict[str, int] = {}
    en_counts: dict[str, int] = {}
    for e in existing:
        fa_counts[e["fa"]] = fa_counts.get(e["fa"], 0) + 1
        en_counts[e["en"].casefold()] = en_counts.get(e["en"].casefold(), 0) + 1

    out: list[dict[str, str]] = []
    skipped = 0
    for fa, en, cat in EXTRA:
        fa, en, cat = fa.strip(), en.strip(), cat.strip()
        key = (fa.casefold(), en.casefold())
        if key in seen_pairs:
            skipped += 1
            continue
        if fa_counts.get(fa, 0) >= 3:
            skipped += 1
            continue
        if en_counts.get(en.casefold(), 0) >= 3:
            skipped += 1
            continue
        seen_pairs.add(key)
        fa_counts[fa] = fa_counts.get(fa, 0) + 1
        en_counts[en.casefold()] = en_counts.get(en.casefold(), 0) + 1
        out.append({"fa": fa, "en": en, "cat": cat})

    dest.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    entries = validate_all()
    print(f"wrote {len(out)} extra terms ({skipped} skipped); dictionary now {len(entries)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
