const normalize = (value) => value.replace(/\s+/g, " ").trim();

/** Translate one known UI string while preserving surrounding whitespace. */
export function translatePersian(value) {
    if (typeof value !== "string" || !value.trim()) return value;
    const leading = value.match(/^\s*/)?.[0] || "";
    const trailing = value.match(/\s*$/)?.[0] || "";
    const key = normalize(value);
    const translated = UI_TRANSLATIONS[key];
    if (translated) return `${leading}${translated}${trailing}`;
    for (const [pattern, replacer] of DYNAMIC_TRANSLATIONS) {
        if (pattern.test(key)) return `${leading}${key.replace(pattern, replacer)}${trailing}`;
    }
    return value;
}

const SKIP_ELEMENTS = new Set(["SCRIPT", "STYLE", "NOSCRIPT"]);
const TRANSLATABLE_ATTRIBUTES = ["aria-label", "aria-description", "title", "placeholder", "alt"];

function isUserContent(element) {
    if (!element) return true;
    return Boolean(
        element.closest(
            "[data-no-translate], textarea, input, [contenteditable='true'], .raw-transcription, .user-content, .markdown-content",
        ),
    );
}

function translateAttributes(element) {
    if (!(element instanceof Element)) return;
    for (const attribute of TRANSLATABLE_ATTRIBUTES) {
        const value = element.getAttribute(attribute);
        if (value) {
            const translated = translatePersian(value);
            if (translated !== value) element.setAttribute(attribute, translated);
        }
    }
}

function translateRoot(root) {
    if (!root) return;
    translateAttributes(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    let node;
    while ((node = walker.nextNode())) nodes.push(node);
    for (const textNode of nodes) {
        const parent = textNode.parentElement;
        if (!parent || SKIP_ELEMENTS.has(parent.tagName) || isUserContent(parent)) continue;
        const translated = translatePersian(textNode.nodeValue);
        if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
    }
    root.querySelectorAll("*").forEach(translateAttributes);
}

/** Set the document language/direction before React renders. */
export function setPersianDocument() {
    if (typeof document === "undefined") return;
    document.documentElement.lang = "fa-IR";
    document.documentElement.dir = "rtl";
    document.documentElement.dataset.locale = "fa-IR";
    document.body?.setAttribute("dir", "rtl");
}

/**
 * Install a small observer because many legacy screens render their copy in
 * feature components. It only translates the allow-listed strings above and
 * therefore cannot alter clinical content or mixed Persian/English input.
 */
export function installPersianLocale() {
    if (typeof document === "undefined") return () => {};
    setPersianDocument();
    // Observe the body rather than only #root: Chakra dialogs and tooltips
    // are rendered in a portal next to the root element.
    const root = document.body;
    if (!root) return () => {};
    translateRoot(root);
    const observer = new MutationObserver((mutations) => {
        for (const mutation of mutations) {
            if (mutation.type === "characterData") {
                const parent = mutation.target.parentElement;
                if (parent && !isUserContent(parent)) {
                    const translated = translatePersian(mutation.target.nodeValue);
                    if (translated !== mutation.target.nodeValue) {
                        mutation.target.nodeValue = translated;
                    }
                }
            } else if (mutation.type === "attributes") {
                translateAttributes(mutation.target);
            } else {
                mutation.addedNodes.forEach((node) => {
                    if (node.nodeType === Node.ELEMENT_NODE) translateRoot(node);
                    else if (node.nodeType === Node.TEXT_NODE) {
                        const parent = node.parentElement;
                        if (parent && !isUserContent(parent)) {
                            node.nodeValue = translatePersian(node.nodeValue);
                        }
                    }
                });
            }
        }
    });
    observer.observe(root, {
        childList: true,
        subtree: true,
        characterData: true,
        attributes: true,
        attributeFilter: TRANSLATABLE_ATTRIBUTES,
    });
    return () => observer.disconnect();
}

export function usePersianLocale() {
    useEffect(() => installPersianLocale(), []);
}

export function toPersianDigits(value) {
    return String(value).replace(/[0-9]/g, (digit) => "۰۱۲۳۴۵۶۷۸۹"[Number(digit)]);
}

export function formatPersianDate(value, options = {}) {
    if (!value) return "";
    const date = value instanceof Date ? value : new Date(value);
    if (Number.isNaN(date.getTime())) return value;
    return new Intl.DateTimeFormat("fa-IR", options).format(date);
}

export function isPersianOrMixed(value) {
    return /[\u0600-\u06ff]/.test(String(value || ""));
}
